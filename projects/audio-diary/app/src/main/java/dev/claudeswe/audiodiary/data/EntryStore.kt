package dev.claudeswe.audiodiary.data

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import java.io.File

/**
 * Plain-file storage, one directory per entry:
 *
 * ```
 * entries/<id>/meta.json        status, duration, export location
 * entries/<id>/seg_000.m4a ...  audio segments, in order
 * entries/<id>/seg_000.txt ...  transcript of each segment (written as each one finishes)
 * entries/<id>/body.txt         the transcript alone (what the editor shows)
 * shared/<id>.txt               the assembled text file (header + transcript) for sharing/export
 * ```
 *
 * `shared/` is the only directory exposed through the FileProvider, so a share grant can never reach audio
 * or metadata.
 *
 * No database: the directory listing *is* the index, which keeps the data inspectable and easy to back up.
 */
class EntryStore(val root: File, val sharedDir: File = File(root.parentFile, "shared")) {
    private val _version = MutableStateFlow(0)

    /** Bumped on every write so the UI can re-read. */
    val version: StateFlow<Int> = _version

    init {
        root.mkdirs()
        sharedDir.mkdirs()
    }

    /** Ids are generated by [create]; anything else (e.g. `../x`) is rejected so no path can escape [root]. */
    fun dir(id: String): File {
        require(ID_PATTERN.matches(id)) { "Invalid entry id" }
        return File(root, id)
    }

    fun exists(id: String): Boolean = ID_PATTERN.matches(id) && metaFile(id).exists()
    fun metaFile(id: String) = File(dir(id), "meta.json")
    fun bodyFile(id: String) = File(dir(id), "body.txt")
    fun textFile(id: String) = File(sharedDir, dir(id).name + ".txt")
    fun segmentAudio(id: String, index: Int) = File(dir(id), "seg_%03d.m4a".format(index))
    fun segmentText(audio: File) = File(audio.parentFile, audio.nameWithoutExtension + ".txt")

    /** Creates a new entry directory with a unique, time-based id. */
    @Synchronized
    fun create(createdAt: Long, baseId: String = Format.entryId(createdAt)): Entry {
        var id = baseId
        var n = 2
        while (dir(id).exists()) id = "$baseId-${n++}"
        dir(id).mkdirs()
        val entry = Entry(id = id, createdAt = createdAt)
        save(entry)
        return entry
    }

    /** Writes [entry]'s metadata. Does nothing if the entry was deleted (never resurrects it). */
    @Synchronized
    fun save(entry: Entry) {
        if (!dir(entry.id).isDirectory) return
        writeAtomic(metaFile(entry.id), entry.toJson())
        _version.value++
    }

    fun load(id: String): Entry? = runCatching { Entry.fromJson(metaFile(id).readText()) }
        .getOrNull()
        ?.takeIf { it.id == id }

    /** Applies [change] to the stored entry (if it still exists) and saves it. */
    @Synchronized
    fun update(id: String, change: (Entry) -> Entry): Entry? {
        val current = load(id) ?: return null
        val next = change(current).copy(id = id)
        save(next)
        return next
    }

    /** All entries, newest first. */
    fun list(): List<Entry> =
        (root.listFiles() ?: emptyArray())
            .filter { it.isDirectory && ID_PATTERN.matches(it.name) }
            .mapNotNull { load(it.name) }
            .sortedByDescending { it.createdAt }

    /** Audio segments in recording order. */
    fun segments(id: String): List<File> =
        (dir(id).listFiles() ?: emptyArray())
            .filter { it.name.startsWith("seg_") && it.extension == "m4a" }
            .sortedBy { it.name }

    fun readBody(id: String): String = bodyFile(id).takeIf { it.exists() }?.readText() ?: ""

    /** Writes the transcript and the shareable text file; returns the text-file contents. */
    @Synchronized
    fun writeBody(entry: Entry, body: String): String? {
        if (!dir(entry.id).isDirectory) return null
        writeAtomic(bodyFile(entry.id), body.trim() + "\n")
        val text = Format.textFile(entry.createdAt, entry.durationMs, body)
        writeAtomic(textFile(entry.id), text)
        _version.value++
        return text
    }

    /** Removes per-segment transcripts so the next transcription run starts from scratch. */
    @Synchronized
    fun clearSegmentTranscripts(id: String) {
        segments(id).forEach { segmentText(it).delete() }
    }

    @Synchronized
    fun delete(id: String) {
        dir(id).deleteRecursively()
        textFile(id).delete()
        _version.value++
    }

    private fun writeAtomic(target: File, content: String) {
        val tmp = File(target.parentFile, target.name + ".tmp")
        tmp.writeText(content)
        if (!tmp.renameTo(target)) {
            target.delete()
            tmp.renameTo(target)
        }
    }

    companion object {
        /** `2026-11-01_20-45-12`, optionally with a `-2` style suffix. */
        val ID_PATTERN = Regex("^\\d{4}-\\d{2}-\\d{2}_\\d{2}-\\d{2}-\\d{2}(-\\d{1,4})?$")

        /** Joins per-segment transcripts. Segments are cut mid-speech, so they're joined with a space. */
        fun assemble(parts: List<String>): String =
            parts.map { it.trim() }.filter { it.isNotEmpty() }.joinToString(" ")
    }
}
