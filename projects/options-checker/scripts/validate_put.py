"""Validate the synthetic put-write against the real Cboe PUT index (S9 gate).

Downloads the free histories (or reads them from --data), runs the replication and
a split-sample check, and writes docs/validation/put-replication.md plus an SVG chart.

    python scripts/validate_put.py --data ~/.cache/occheck
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from occheck import data
from occheck.backtest.putwrite import compare_to_index, put_write

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "docs" / "validation"
GATE = {"monthly_corr": 0.9, "cagr_diff": 0.015}
GRID = np.round(np.arange(0.80, 1.001, 0.01), 2)
HALVES = (("2007-06-01", "2016-12-31"), ("2017-01-01", "2099-12-31"))


def load(kind: str, folder: Path | None) -> data.Series:
    path = folder / f"{kind}.csv" if folder else None
    if path is None or not path.exists():
        path = data.download(kind, folder)
    return data.load_csv(path.read_text())


def run(dates, s, v, r, put, lo, hi, ratio):
    m = (dates >= np.datetime64(lo)) & (dates <= np.datetime64(hi))
    res = put_write(dates[m], s[m], v[m], r[m], atm_vol_ratio=ratio)
    return res, compare_to_index(res, put.dates, put.values)


def svg_chart(res, put) -> str:
    common, ia, ib = np.intersect1d(res.dates, put.dates, return_indices=True)
    a = res.equity[ia] / res.equity[ia][0]
    b = put.values[ib] / put.values[ib][0]
    step = max(1, len(common) // 400)
    a, b, common = a[::step], b[::step], common[::step]
    w, h, left, pad = 720, 300, 48, 16
    lo, hi = np.log(min(a.min(), b.min())), np.log(max(a.max(), b.max()))

    def pts(v):
        xs = left + np.arange(len(v)) / (len(v) - 1) * (w - left - pad)
        ys = pad + (1 - (np.log(v) - lo) / (hi - lo)) * (h - 2 * pad - 14)
        return " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys, strict=True))

    years = common.astype("datetime64[Y]").astype(int) + 1970
    labels = "".join(
        f'<text x="{left + i / (len(common) - 1) * (w - left - pad):.0f}" y="{h - 2}" '
        f'font-size="11" fill="#4a5a70">{y}</text>'
        for i, y in enumerate(years)
        if i > 0 and y != years[i - 1] and y % 4 == 0
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'font-family="Arial, sans-serif">'
        f'<rect width="{w}" height="{h}" fill="#f7f9fb"/>'
        f'<polyline points="{pts(b)}" fill="none" stroke="#17253a" stroke-width="2"/>'
        f'<polyline points="{pts(a)}" fill="none" stroke="#b4233c" stroke-width="1.5" '
        f'stroke-dasharray="5 3"/>{labels}'
        f'<text x="{left}" y="14" font-size="12" fill="#17253a">Cboe PUT index (solid) vs '
        f"synthetic replication (dashed), growth of 1, log scale</text></svg>"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=None, help="folder with SPX/VIX/DTB3/PUT.csv")
    args = ap.parse_args()
    spx, vix, tb, put = (load(k, args.data) for k in ("SPX", "VIX", "DTB3", "PUT"))
    dates, (s, v, r) = data.align(spx, vix, tb)
    rows = []
    for ratio in (1.0, 0.9):
        _, c = run(dates, s, v, r, put, *("2007-06-01", "2099-12-31"), ratio)
        rows.append((ratio, c))
    split = []
    for fit, test in (HALVES, HALVES[::-1]):
        best = min(GRID, key=lambda g: abs(run(dates, s, v, r, put, *fit, g)[1]["cagr_diff"]))
        split.append((fit, test, best, run(dates, s, v, r, put, *test, best)[1]))
    res, _ = run(dates, s, v, r, put, "2007-06-01", "2099-12-31", 0.9)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "put-replication.svg").write_text(svg_chart(res, put))

    def verdict(c):
        ok = c["monthly_corr"] >= GATE["monthly_corr"] and abs(c["cagr_diff"]) <= GATE["cagr_diff"]
        return "pass" if ok else "fail"

    c0 = rows[0][1]
    md = [
        "# Synthetic put-write vs the Cboe PUT index",
        "",
        f"Generated by `scripts/validate_put.py` on data through {c0['end']}. "
        f"Daily PUT history is complete from mid-2007, so the comparison starts {c0['start']}.",
        "",
        f"Gate (design §4): monthly-return correlation ≥ {GATE['monthly_corr']} and CAGR within "
        f"±{GATE['cagr_diff'] * 100:.1f} points a year.",
        "",
        "![PUT vs synthetic](put-replication.svg)",
        "",
        "## Full period",
        "",
        "| ATM vol = VIX × | Months | Monthly corr | CAGR synthetic | CAGR PUT | Difference | "
        "Tracking error | Max drawdown synthetic / PUT | Gate |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for ratio, c in rows:
        md.append(
            f"| {ratio:.2f} | {c['months']:.0f} | {c['monthly_corr']:.3f} | {c['cagr_synth']:.2%} | "
            f"{c['cagr_index']:.2%} | {c['cagr_diff'] * 100:+.2f} pts | {c['tracking_error']:.2%} | "
            f"{c['max_dd_synth']:.1%} / {c['max_dd_index']:.1%} | {verdict(c)} |"
        )
    md += [
        "",
        "## Split-sample check of the vol ratio",
        "",
        "The ratio is chosen on one half of the data (closest CAGR) and tested on the other half.",
        "",
        "| Fit on | Best ratio | Test on | Test corr | Test CAGR difference | Gate |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for fit, test, best, c in split:
        md.append(
            f"| {fit[0][:4]}–{fit[1][:4] if fit[1] < '2099' else 'now'} | {best:.2f} | "
            f"{test[0][:4]}–{test[1][:4] if test[1] < '2099' else 'now'} | {c['monthly_corr']:.3f} | "
            f"{c['cagr_diff'] * 100:+.2f} pts | {verdict(c)} |"
        )
    md += [
        "",
        "## Reading this",
        "",
        "- Using VIX itself as at-the-money vol overstates put-selling returns. VIX averages "
        "variance across all strikes, including expensive out-of-the-money puts, so it sits above "
        "at-the-money implied vol. That makes the synthetic premium too rich.",
        "- Scaling VIX by 0.9 removes most of that bias, and the ratio carries across the two halves. "
        "0.9 is the model default; it was chosen on 2007–2016 and holds on 2017–now.",
        "- Remaining differences: expiry settles at the close instead of the morning opening print, "
        "the strike is exactly at the money instead of the listed strike, and Cboe's collateral "
        "rules (1- and 3-month bills) differ slightly from the 3-month rate used here.",
        "- The index has no trading costs. Backtests of real trading add a bid-ask cost (S10).",
        "",
    ]
    (OUT / "put-replication.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
